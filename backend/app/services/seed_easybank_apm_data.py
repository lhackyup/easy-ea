def seed_easybank_apm_portfolio(db: Session) -> Dict[str, int]:
    """Updates existing apps and inserts 50 realistic business applications in EasyBank Global (EASY)."""
    model = db.query(ModelWorkspace).filter(ModelWorkspace.code == "EASY").first()
    if not model:
        raise RuntimeError("Workspace model with code 'EASY' not found in database.")

    stereo = db.query(ElementStereotype).filter(ElementStereotype.id == "stereo-business-app").first()
    stereo_id = stereo.id if stereo else "stereo-business-app"

    updated_count = 0
    created_count = 0

    # 1. Enrich existing 9 applications
    for app_id, raw_props in EXISTING_APPS_DATA.items():
        props = dict(raw_props)
        if app_id in APP_CODE_AND_SHORT_NAMES:
            c, sn = APP_CODE_AND_SHORT_NAMES[app_id]
            props['apm_app_code'] = c
            props['apm_short_name'] = sn
        elem = db.query(ArchimateElement).filter(
            ArchimateElement.id == app_id,
            ArchimateElement.model_id == model.id
        ).first()
        if elem:
            merged_props = dict(elem.properties or {})
            merged_props.update(props)
            elem.properties = merged_props
            elem.stereotype_id = stereo_id
            elem.is_reference = False
            elem.layer = "Application"
            elem.type = "ApplicationComponent"
            updated_count += 1

    # 2. Insert or update 50 simulated business applications
    for app in NEW_SIMULATED_APPS:
        app_id = app["id"]
        props = {k: v for k, v in app.items() if k.startswith("apm_")}
        if app_id in APP_CODE_AND_SHORT_NAMES:
            c, sn = APP_CODE_AND_SHORT_NAMES[app_id]
            props['apm_app_code'] = c
            props['apm_short_name'] = sn
        else:
            props.setdefault('apm_app_code', f"AP{abs(hash(app_id)) % 9000 + 1000}"[:6])
            props.setdefault('apm_short_name', (app.get('name') or 'App')[:12])

        elem = db.query(ArchimateElement).filter(
            ArchimateElement.id == app_id,
            ArchimateElement.model_id == model.id
        ).first()

        if not elem:
            elem = ArchimateElement(
                id=app_id,
                model_id=model.id,
                name=app["name"],
                type="ApplicationComponent",
                layer="Application",
                documentation=app["documentation"],
                properties=props,
                stereotype_id=stereo_id,
                is_reference=False,
                package_id="pkg-apm"
            )
            db.add(elem)
            created_count += 1
        else:
            elem.name = app["name"]
            elem.documentation = app["documentation"]
            merged = dict(elem.properties or {})
            merged.update(props)
            elem.properties = merged
            elem.stereotype_id = stereo_id
            elem.is_reference = False
            elem.package_id = "pkg-apm"
            updated_count += 1

    db.commit()
    return {"updated": updated_count, "created": created_count, "total_model_apps": len(EXISTING_APPS_DATA) + len(NEW_SIMULATED_APPS)}


